#!/usr/bin/env python3
"""Generate a per-copy env file for the Supabase stack from .env.example.

Fills every blank secret with a fresh random value and points the copy at its
own gateway port.

JWT signing is asymmetric (ticket #152): one RSA-3072 key pair per copy,
generated by bin/gen-keys.mjs (node does the crypto; Python's standard
library cannot generate RSA keys). The private JWK is written to a
GoTrue-only env file (.env.<copy>.gotrue) and never to the shared file, so
no other container ever sees it. The public JWKS goes into JWT_JWKS —
consumed by everything that verifies tokens: PostgREST, Realtime, Storage,
the functions container and the note server. ANON_KEY and
SERVICE_ROLE_KEY are minted as RS256 JWTs signed by the same key. Two
boot-mandated HS256 hold-outs remain (Storage's static secret and
Realtime's metrics secret) and are recorded as open gaps in
docs/adr/0003-asymmetric-jwt-signing.md.

Usage:
    python3 bin/gen-env.py --copy ironsworn --port 8000 [--out .env.ironsworn]
    python3 bin/gen-env.py --copy starforged --port 8001 [--out .env.starforged]
"""

import argparse
import base64
import json
import os
import secrets
import subprocess
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
EXAMPLE = os.path.join(os.path.dirname(HERE), ".env.example")

COPY_PORTS = {"ironsworn": "8000", "starforged": "8001"}
SITE_PORTS = {"ironsworn": "8080", "starforged": "8081"}


def run_gen_keys() -> dict:
    """Runs bin/gen-keys.mjs and returns its JSON output (all key material)."""
    result = subprocess.run(
        ["node", os.path.join(HERE, "gen-keys.mjs")],
        capture_output=True,
    )
    if result.returncode != 0:
        print(
            "gen-env: node bin/gen-keys.mjs failed: "
            + result.stderr.decode(errors="replace").strip(),
            file=sys.stderr,
        )
        raise SystemExit(1)
    try:
        keys = json.loads(result.stdout)
    except json.JSONDecodeError as error:
        print(f"gen-env: could not parse gen-keys output: {error}", file=sys.stderr)
        raise SystemExit(1)
    expected = {"JWT_KEYS", "JWT_JWKS", "ANON_KEY", "SERVICE_ROLE_KEY"}
    if set(keys) != expected or not all(keys.values()):
        print("gen-env: gen-keys output incomplete", file=sys.stderr)
        raise SystemExit(1)
    return keys


def fresh_secrets() -> dict:
    keys = run_gen_keys()

    # Exactly 32 chars: realtime requires 32 bytes for AES-256-GCM.
    realtime_db_enc_key_gcm = secrets.token_hex(16)

    return {
        "POSTGRES_PASSWORD": secrets.token_urlsafe(32),
        # The private signing JWK: GoTrue only. Written to its own env file
        # (see main), never to the shared file other containers read.
        "JWT_KEYS": json.dumps(keys["JWT_KEYS"], separators=(",", ":")),
        # The public JWKS: every token verifier (PostgREST, Realtime,
        # Storage, functions, the note server).
        "JWT_JWKS": json.dumps(keys["JWT_JWKS"], separators=(",", ":")),
        "ANON_KEY": keys["ANON_KEY"],
        "SERVICE_ROLE_KEY": keys["SERVICE_ROLE_KEY"],
        # Storage's static JWT secret: the pinned storage image refuses to
        # boot without one, and it signs Storage's short-lived object URLs.
        # It never signs or verifies user tokens on the other services, and
        # is one of the two HS256 hold-outs recorded as open gaps in
        # docs/adr/0003 (ticket #152).
        "AUTH_JWT_SECRET": secrets.token_urlsafe(36),
        # Realtime's metrics endpoint scrape secret: the pinned realtime
        # image refuses to boot without one. It grants metric reads on an
        # endpoint the gateway never routes, and never touches user tokens.
        "METRICS_JWT_SECRET": secrets.token_urlsafe(36),
        "SECRET_KEY_BASE": secrets.token_urlsafe(48),
        "REALTIME_DB_ENC_KEY_GCM": realtime_db_enc_key_gcm,
        "S3_PROTOCOL_ACCESS_KEY_ID": secrets.token_hex(16),
        "S3_PROTOCOL_ACCESS_KEY_SECRET": secrets.token_hex(32),
        "PG_META_CRYPTO_KEY": secrets.token_urlsafe(32),
    }


def main() -> int:
    parser = argparse.ArgumentParser(description="Generate a per-copy Supabase env file.")
    parser.add_argument("--copy", required=True, help="Copy name, e.g. ironsworn or starforged.")
    parser.add_argument("--port", help="Gateway host port (defaults: 8000/8001 for the two game systems).")
    parser.add_argument("--site-port", help="Site host port (defaults: 8080/8081 for the two game systems).")
    parser.add_argument("--out", help="Output path (default: .env.<copy> next to .env.example).")
    args = parser.parse_args()

    port = args.port or COPY_PORTS.get(args.copy, "8000")
    site_port = args.site_port or SITE_PORTS.get(args.copy, "8080")
    out = args.out or os.path.join(os.path.dirname(EXAMPLE), f".env.{args.copy}")

    lines = open(EXAMPLE).read().splitlines(keepends=False)
    values = fresh_secrets()
    # The private signing JWK never enters the shared env file: it lives in a
    # GoTrue-only file beside it, and the shared file points the template at
    # that path (the auth service's env_file list). The pinned GoTrue also
    # refuses to boot without GOTRUE_JWT_SECRET even when keys are set, so a
    # random dead value rides along: signing uses the JWK, verification is
    # pinned to RS256, and the secret is never consulted (see ADR 0003).
    gotrue_keys_file = os.path.basename(out) + ".gotrue"
    gotrue_values = {
        "GOTRUE_JWT_KEYS": values.pop("JWT_KEYS"),
        "GOTRUE_JWT_SECRET": secrets.token_urlsafe(36),
    }
    values["JWT_KEYS_FILE"] = gotrue_keys_file
    values.update(
        {
            "ENV_FILE": os.path.basename(out),
            "GAME_SYSTEM": args.copy,
            "API_GW_HTTP_PORT": port,
            "SUPABASE_PUBLIC_URL": f"http://localhost:{port}",
            "API_EXTERNAL_URL": f"http://localhost:{port}/auth/v1",
            "SITE_HTTP_PORT": site_port,
            "SITE_URL": f"http://localhost:{site_port}",
        }
    )

    filled = []
    for line in lines:
        stripped = line.strip()
        if not stripped or stripped.startswith("#") or "=" not in line:
            filled.append(line)
            continue
        key, current = line.split("=", 1)
        key = key.strip()
        if key in values:
            filled.append(f"{key}={values[key]}")
        elif current.strip() == "" and key not in values:
            # A blank we do not generate (optional asymmetric keys): keep the
            # example's default so legacy API key mode stays on.
            filled.append(line)
        else:
            filled.append(line)

    # Storage's own upload ceiling (FILE_SIZE_LIMIT, bytes) derives from the
    # one image size setting CHAT_IMAGE_MAX_MB (ticket #118), so the bucket
    # cap (apply.sh, every start), the client cap (site build) and Storage
    # follow it together on every deploy.
    image_max_mb = 10
    for line in filled:
        if line.startswith("CHAT_IMAGE_MAX_MB="):
            raw = line.split("=", 1)[1].strip()
            if raw.isdigit() and int(raw) > 0:
                image_max_mb = int(raw)
    derived_limit = f"FILE_SIZE_LIMIT={image_max_mb * 1024 * 1024}"
    for i, line in enumerate(filled):
        if line.startswith("FILE_SIZE_LIMIT="):
            filled[i] = derived_limit
            break
    else:
        for i, line in enumerate(filled):
            if line.startswith("CHAT_IMAGE_MAX_MB="):
                filled.insert(i + 1, derived_limit)
                break
        else:
            filled.append(derived_limit)

    with open(out, "w") as fh:
        fh.write("\n".join(filled) + "\n")

    # The GoTrue-only file: the private signing JWK, beside the main env
    # file, git-ignored like it. Only the auth service's env_file reads it.
    gotrue_out = os.path.join(os.path.dirname(out), gotrue_keys_file)
    with open(gotrue_out, "w") as fh:
        for key, value in gotrue_values.items():
            fh.write(f"{key}={value}\n")

    missing = [k for k, v in values.items() if not v]
    if missing:
        print(f"gen-env: refusing to write, blank values for: {', '.join(missing)}", file=sys.stderr)
        return 1
    print(f"gen-env: wrote {out} (keep it secret, never commit it)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
